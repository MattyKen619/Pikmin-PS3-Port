#!/usr/bin/env python3
"""PS3 port: writes a binary file as a C array (the vertex program cgcomp assembles, the SPU mixer program).

    python3 tools/ps3/bin2h.py INPUT NAME OUTPUT.h [ALIGNMENT]
"""
import sys


def main():
    if len(sys.argv) not in (4, 5):
        print(__doc__)
        return 2
    align = int(sys.argv[4]) if len(sys.argv) == 5 else 16
    data = open(sys.argv[1], "rb").read()
    name = sys.argv[2]
    lines = ["// generated by tools/ps3/bin2h.py from %s: do not edit" % sys.argv[1].replace("\\", "/"),
             "static const unsigned char %s[%d] __attribute__((aligned(%d))) = {" % (name, len(data), align)]
    for i in range(0, len(data), 16):
        lines.append("\t" + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    with open(sys.argv[3], "w") as f:
        f.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
