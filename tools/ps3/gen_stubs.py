#!/usr/bin/env python3
"""
PS3 port: generate placeholder implementations ("stubs") of the Nintendo SDK functions the game still
needs, using the exact declarations from include/Dolphin (read with libclang).

Input:  build/ps3link/undefined.json (from tools/ps3/link_check.py)
Output: platform/ps3/stubs/sdk_stubs.gen.cpp

Each stub reports its first call through PS3_STUB() and returns a zero value. They exist so the whole
game links; Phase 3/4/5 replace them subsystem by subsystem with real PS3 implementations.

Usage:
  python3 tools/ps3/gen_stubs.py --bindings /path/to/clang/bindings/python --libclang /path/to/libclang.so
"""
import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from gcc_check import DEFINES  # noqa: E402

SDK_HEADERS = ["Dolphin/os.h", "Dolphin/gx.h", "Dolphin/dvd.h", "Dolphin/card.h", "Dolphin/pad.h", "Dolphin/vi.h",
               "Dolphin/ar.h", "Dolphin/ai.h", "Dolphin/dsp.h", "Dolphin/hio.h", "Dolphin/PPCArch.h",
               "Dolphin/hw_regs.h"]

# Globals are hand-written in platform/ps3/stubs/sdk_globals.cpp (they need sensible values).
HANDWRITTEN = {"GXWGFifo", "__DSPRegs", "__OSBusClock", "__OSCurrHeap"}

OUT = ROOT / "platform/ps3/stubs/sdk_stubs.gen.cpp"
IMPL_DIR = ROOT / "platform/ps3/sdk"  # real implementations; their functions get no stub


def implemented_functions():
    """Names of functions defined at file scope in the platform SDK layer."""
    import re
    names = set()
    rx = re.compile(r"^[A-Za-z_][\w\s\*]*?\b([A-Za-z_]\w*)\s*\([^)]*\)\s*(\{|$)")
    for f in sorted(IMPL_DIR.glob("*.cpp")):
        for line in f.read_text(errors="ignore").splitlines():
            m = rx.match(line)
            if m and not line.startswith(("static", "return", "if", "for", "while", "switch")):
                names.add(m.group(1))
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bindings", required=True)
    ap.add_argument("--libclang", required=True)
    args = ap.parse_args()
    sys.path.insert(0, args.bindings)
    import clang.cindex as ci
    ci.Config.set_library_file(args.libclang)

    rows = json.loads((ROOT / "build/ps3link/undefined.json").read_text())
    implemented = implemented_functions()
    wanted = sorted(r["symbol"] for r in rows
                    if r["group"].startswith("sdk:") and r["symbol"] not in HANDWRITTEN and r["symbol"] not in implemented)
    print(f"implemented in platform/ps3/sdk: {len([r for r in rows if r['symbol'] in implemented])} SDK symbols")

    probe = "".join(f'#include "{h}"\n' for h in SDK_HEADERS)
    idx = ci.Index.create()
    tu = idx.parse("probe.cpp", unsaved_files=[("probe.cpp", probe)],
                   args=["--target=powerpc64-unknown-elf", "-x", "c++", "-std=gnu++14", "-funsigned-char", "-nostdinc",
                         "-isystem", str(ROOT / "include/stl"), "-I", str(ROOT / "include"), "-w", *DEFINES])
    errs = [d for d in tu.diagnostics if d.severity >= ci.Diagnostic.Error]
    if errs:
        for d in errs[:10]:
            print("probe error:", d)
        sys.exit(1)

    decls = {}
    for cur in tu.cursor.walk_preorder():
        if cur.kind == ci.CursorKind.FUNCTION_DECL and cur.spelling in wanted and cur.spelling not in decls:
            decls[cur.spelling] = cur

    missing = [w for w in wanted if w not in decls]
    lines = [
        "// GENERATED by tools/ps3/gen_stubs.py - do not edit by hand; regenerate after changing the SDK set.",
        "// Placeholder Nintendo SDK functions for the PS3 port. Each one reports its first call and returns zero.",
        "// They let the whole game link; real PS3 implementations replace them subsystem by subsystem.",
        "",
    ]
    lines += [f'#include "{h}"' for h in SDK_HEADERS]
    lines += ['#include "ps3/stub.h"', "", 'extern "C" {', ""]
    by_header = {}
    for name in wanted:
        if name not in decls:
            continue
        c = decls[name]
        hdr = os.path.relpath(c.location.file.name, ROOT / "include") if c.location.file else "?"
        by_header.setdefault(hdr, []).append(c)
    for hdr in sorted(by_header):
        lines.append(f"// ---- {hdr}")
        for c in by_header[hdr]:
            params = [a.type.spelling for a in c.get_arguments()]
            if c.type.kind == ci.TypeKind.FUNCTIONPROTO and c.type.is_function_variadic():
                params.append("...")
            ret = c.result_type.spelling
            sig = f"{ret} {c.spelling}({', '.join(params) if params else 'void'})"
            if c.result_type.kind == ci.TypeKind.VOID:
                body = f'{{ PS3_STUB("{c.spelling}"); }}'
            else:
                body = f'{{ PS3_STUB("{c.spelling}"); return {{}}; }}'
            lines.append(f"{sig} {body}")
        lines.append("")
    lines += ['} // extern "C"', ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"stubs written: {sum(len(v) for v in by_header.values())} -> {OUT.relative_to(ROOT)}")
    if missing:
        print("not declared in SDK headers (need manual stubs):", ", ".join(missing))


if __name__ == "__main__":
    main()
